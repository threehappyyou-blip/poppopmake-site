  var CURRENCIES = ['KRW', 'JPY', 'USD', 'EUR', 'GBP', 'CNY', 'TWD', 'HKD', 'SGD', 'AUD', 'CAD', 'NZD', 'INR', 'PHP', 'THB', 'VND', 'IDR', 'MYR', 'MXN', 'BRL', 'CHF', 'SEK', 'NOK', 'DKK'];
  function defaultCurrency() {
    var list = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en-US']);
    for (var i = 0; i < list.length; i++) {
      var m = String(list[i]).match(/[-_]([A-Za-z]{2})\b/);
      if (m && REGION_CUR[m[1].toUpperCase()]) return REGION_CUR[m[1].toUpperCase()];
    }
    if (lang === 'ko') return 'KRW';
    if (lang === 'ja') return 'JPY';
    return 'USD';
  }
  function currencyName(code) {
    try { return new Intl.DisplayNames([locale()], { type: 'currency' }).of(code); } catch (e) { return code; }
  }
  function money(minor, cur, opts) {
    var d = root.VaultBudget ? root.VaultBudget.digits(cur) : 2;
    var v = minor / Math.pow(10, d);
    try {
      return new Intl.NumberFormat(locale(), { style: 'currency', currency: cur, minimumFractionDigits: d, maximumFractionDigits: d,
        signDisplay: opts && opts.sign ? 'exceptZero' : 'auto' }).format(v);
    } catch (e) { return (opts && opts.sign && v > 0 ? '+' : '') + v.toFixed(d) + ' ' + cur; }
  }
  function monthLabel(ym) {
    var d = new Date(Date.UTC(+ym.slice(0, 4), +ym.slice(5, 7) - 1, 15));
    return new Intl.DateTimeFormat(locale(), { year: 'numeric', month: 'long', timeZone: 'UTC' }).format(d);
  }
  function shortMonth(ym) {
    var d = new Date(Date.UTC(+ym.slice(0, 4), +ym.slice(5, 7) - 1, 15));
    return new Intl.DateTimeFormat(locale(), { month: 'short', timeZone: 'UTC' }).format(d);
  }
  function dayLabel(date) {
    var d = new Date(Date.UTC(+date.slice(0, 4), +date.slice(5, 7) - 1, +date.slice(8, 10)));
    return new Intl.DateTimeFormat(locale(), { month: 'short', day: 'numeric', weekday: 'short', timeZone: 'UTC' }).format(d);
  }
  function fullDate(date) {
    var d = new Date(Date.UTC(+date.slice(0, 4), +date.slice(5, 7) - 1, +date.slice(8, 10)));
    return new Intl.DateTimeFormat(locale(), { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'UTC' }).format(d);
  }
  function ago(ts) {
    if (!ts) return '';
    var now = new Date(), then = new Date(ts);
    var a = Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()), b = Date.UTC(then.getFullYear(), then.getMonth(), then.getDate());
    var n = Math.round((a - b) / 864e5);
    if (n <= 0) return t('ago.today');
    if (n === 1) return t('ago.yesterday');
    return t('ago.days', { n: n });
  }

